// Scans assets/photos/ and writes photos.js (window.PHOTOS = { slot: path }).
// Drop images named after the slots in PROMPTS.md (e.g. argent-investir.jpg), then run:
//   node tools/scan-photos.mjs
// Any slot without a photo keeps its illustrated fallback.
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, extname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "assets", "photos");
const exts = new Set([".jpg", ".jpeg", ".png", ".webp"]);
const photos = {};
for (const f of readdirSync(dir).sort()) {
  if (exts.has(extname(f).toLowerCase())) photos[basename(f, extname(f))] = `assets/photos/${f}`;
}
writeFileSync(join(root, "photos.js"), `// Generated by tools/scan-photos.mjs — do not edit.\nwindow.PHOTOS = ${JSON.stringify(photos, null, 2)};\n`);
console.log(`${Object.keys(photos).length} photo(s):`, Object.keys(photos).join(", ") || "(none, fallback art everywhere)");
